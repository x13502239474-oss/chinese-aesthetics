<p><strong>神韵 vs 风骨：韵味与骨力。</strong>神韵偏柔、偏淡、偏回味，像好茶的回甘；风骨偏刚、偏健、偏力量，像好酒的劲道。二者一阴一阳，共同构成中国艺术的两种理想品格。</p>

