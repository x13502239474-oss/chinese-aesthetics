<p><strong>意境 vs 气韵：氛围与生命。</strong>气韵强调作品的生命气息和节奏，是「活不活」的问题；意境强调作品的精神空间和意味深度，是「深不深」的问题。气韵是意境的前提——一幅死气沉沉的画谈不上意境；意境是气韵的升华——有了生命力，还要把这生命力化成可游可居的精神空间。</p>

