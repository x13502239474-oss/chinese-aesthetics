<p><strong>王夫之</strong>是意象论的高峰。他说：「情与景，虽各有分，而实有合。」又讲「景中生情，情中含景」，好的诗句里情与景是化在一起的。他强调意象的「真实性」——不是照抄生活，而是写出「昭昭心目之间」的真切感受。</p>
