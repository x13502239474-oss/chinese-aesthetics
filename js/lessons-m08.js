<p><strong>郑板桥</strong>用画竹的经验，把意象的生成讲得最生动。他说自己画竹有三个阶段：「眼中之竹」「胸中之竹」「手中之竹」。眼中之竹是看到的实物，胸中之竹是融入了情感和理解的意象，手中之竹是落到纸上的产物。三个阶段层层转化，意象就在「胸中」这一环成形。</p>

