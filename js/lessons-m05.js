<p>殷璠在《河岳英灵集》序里批评过去的选本"都无兴象，但贵轻艳"，又在评语中用"兴象"论诗：评李白"亦多兴象"，评孟浩然"无论兴象，兼复故实"。他不仅提出这个概念，还把它作为选诗和评诗的标准。</p>
