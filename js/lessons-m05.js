<p>"兴"是中国诗学的老传统，指感物起情、托物言志；"象"指形象。"兴象"合起来，指诗中那种由感兴而生、情景交融、有余味无穷之美的意象。叶朗指出，"兴象"是"意象"的一种，它强调诗歌意象的感发性和含蓄性——好的诗不是把意思说尽，而是让人在读的时候被感发、被触动。</p>

