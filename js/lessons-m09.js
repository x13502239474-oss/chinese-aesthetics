<p>五体各有性格：篆书线条均匀圆转，像古人正襟危坐；隶书有波磔，撇捺展开如翅膀；楷书端正，一笔一画讲法度；行书介于楷草之间，流动而可认；草书奔放，线条连绵，几乎就是纸上的舞蹈。学书法常从「永字八法」入手，因为一个「永」字里包含了侧、勒、努、趯、策、掠、啄、磔八种基本笔法。点像鸟翻然侧下，横像勒马用缰，竖像用力，钩像跳跃——每一种笔法都用身体的动作来命名，这说明书法从根本上就是身体的艺术。</p>
