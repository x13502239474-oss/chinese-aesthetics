<p>要理解中国画，先得知道它从哪儿来。宗白华在《论中西画法的渊源与基础》里做了一个溯源的工作：西洋画（油画）的源头是希腊的雕塑和建筑，中国画的源头是书法。这个判断看着简单，其实一下子把很多笼统的说法都理顺了。</p>
