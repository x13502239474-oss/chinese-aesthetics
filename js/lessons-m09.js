<p>郭熙说，好的山水画要让人「可行、可望、可游、可居」，其中「可游、可居」才算上品。这句话把山水画和风景照片彻底分开：照片是给你看的，山水画是让你住进去的。李泽厚把宋元山水分为北宋、南宋、元三个阶段，说北宋是「无我之境」——画面浑然天地，人消融在自然里；到元代，画家的主观情味越来越重。范宽属于前者，倪瓒已经走到后者的门口。</p>

