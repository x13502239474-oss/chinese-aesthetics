<p><strong>第二，</strong>「琳琅满目的世界」是汉代艺术的主题：神话、历史、现实同台演出，汉赋与画像石以铺陈万物表现人对世界的征服。</p>
<p><strong>第三，</strong>「气势与古拙」是汉代艺术的美学风貌：运动、力量、速度构成气势，粗轮廓、不修饰的古拙反而增强力量感，二者浑然一体。</p>
<p><strong>第四，</strong>汉代艺术中经学、谶纬与楚文化幻想并存，形成独特张力；它在气势与古拙中蕴含的生命力，正是通往魏晋审美自觉的桥梁。</p>
