<p>「虚」与「实」是「有」「无」在艺术里的具体形态。叶朗在第一章第五节梳理了这条线索：老子的「虚」不是空洞，而是让万物得以生成的空场。这个思想经过庄子的「心斋」「坐忘」、宗炳的「澄怀味象」，到唐宋变成山水画和书法的核心法则。</p>
