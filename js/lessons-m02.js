<p>远古的歌舞后来一分为二：身体姿态、仪式程序逐渐沉淀为「礼」，歌声、乐舞、饰品逐渐沉淀为「乐」。礼维持秩序，乐陶融情感。这个过程在《尚书》里还留有记忆。</p>
