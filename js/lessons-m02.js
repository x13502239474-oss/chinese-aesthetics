<h2>七、历史联系：自然观的三段演变</h2>
<p>中国人对自然的态度大致走了三步：<strong>孔子比德</strong>，自然是人格的象征；<strong>魏晋畅神</strong>，自然成为独立的审美对象，宗炳说山水「畅神而已」；<strong>唐宋意境</strong>，自然成为情景交融的载体，郭熙讲「可行可望可游可居」，王维讲「诗中有画」。这三步不是互相取代，层层叠加——直到今天，中国人看松竹梅，既看到美，也看到德。</p>

<h2>八、本节总结</h2>
<p><strong>第一，</strong>「知者乐水，仁者乐山」确立了比德传统：自然山水被赋予人格象征，中国人从此很少纯以形状看待自然。</p>
<p><strong>第二，</strong>比德的思维方式建立在自然特征与人的德性的同构关系上，观赏自然同时是观赏自己心中的品格。</p>
<p><strong>第三，</strong>孔子的比德与魏晋宗炳的「澄怀味象」有根本差别：前者是道德化的自然观，后者是审美化的自然观，代表两个阶段的演进。</p>
<p><strong>第四，</strong>比德传统普及到玉、松竹梅等物象，并延伸至「文品即人品」的艺术批评，把自然、人格、艺术串成一条线。</p>
