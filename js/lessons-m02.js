<p>为什么智者配水、仁者配山？后来的儒家学者给了解释：水流动、活泼、通达，像智者机敏的思虑；山稳重、宽厚、蓄养万物，像仁者沉静的胸怀。<span class="term" data-note="把自然物的特征与人的道德品性相比附，自然物因此成为人格的象征；孔子「知者乐水，仁者乐山」是这一传统的确立。">比德</span>就是这种「以物比德」的思维方式。</p>
