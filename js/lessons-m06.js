<p>逸品观念到元代元四家（倪瓒、吴镇、黄公望、王蒙）那里发展成熟，倪瓒的「逸笔草草，写胸中逸气」是其最纯粹的宣言（见 M07-L01）。到明代后期和清代前期，写意画大发展，徐渭、朱耷、石涛、郑板桥等人把「逸」推向狂、怪、纵——叶朗提醒，他们写的意已经不再是「胸中逸气」，而是「血泪斑斑」的愤懑（见 M07-L07）。逸品从一种从容的超脱，演变成激烈的反抗，这是时代变化留下的印记。</p>

