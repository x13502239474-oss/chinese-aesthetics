<p>王弼在《周易略例·明象》里，把庄子的话推进了一步。他讲"意以象尽，象以言著"——意要靠象来显现，象要靠言来说明。但紧接着他来了个转折：言和象都只是工具，得到意就必须忘掉象，得到象就必须忘掉言。</p>
